/**
 * Prebundle apps/mcp into a standalone project for Manufact Cloud.
 *
 * Why: Manufact installs dependencies from the uploaded project's own
 * package.json with a plain package manager, so `@y/schema:
 * workspace:*` cannot resolve there (the managed archive also drops symlinks
 * and node_modules). This script inlines every `@y/*` workspace
 * package with esbuild and writes `apps/mcp/deploy/`:
 *
 *   deploy/package.json          registry deps only, pinned to the installed versions
 *   deploy/src/server.js         src/server.ts with @y/* inlined (mcp-use, zod external)
 *   deploy/skills/y/...   the skill served over MCP
 *   deploy/.gitignore            keeps .mcp-use/ and node_modules/ out of the upload
 *
 * Then `cd apps/mcp/deploy && npx mcp-use deploy --no-github ...` (see
 * docs/DEPLOY.md). No secrets are written: env vars are passed to
 * `mcp-use deploy --env` at deploy time.
 *
 *   pnpm --filter @y/mcp deploy:prepare        # writes apps/mcp/deploy
 */
import * as fs from 'node:fs';
import { createRequire } from 'node:module';
import * as path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
export const MCP_ROOT = path.resolve(here, '..');

/** Registry packages the bundle imports at runtime (kept external, installed by Manufact). */
const RUNTIME_DEPS = ['mcp-use', '@mcp-use/client', 'zod', 'react', 'react-dom'] as const;
/** Needed by `mcp-use build` on the build machine (mcp-use peer). */
const BUILD_DEPS = ['vite'] as const;

function installedVersion(name: string): string {
  // Direct dependencies are linked under apps/mcp/node_modules (some packages don't export ./package.json).
  const pkg = JSON.parse(fs.readFileSync(path.join(MCP_ROOT, 'node_modules', name, 'package.json'), 'utf8')) as { version: string };
  return pkg.version;
}

/** The slice of esbuild's API used here (esbuild's own types aren't resolvable from apps/mcp). */
interface EsbuildPluginBuild {
  onResolve(o: { filter: RegExp }, cb: (args: { path: string }) => { path: string; external: boolean } | undefined): void;
}
interface Esbuild {
  build(options: Record<string, unknown> & { plugins?: { name: string; setup(b: EsbuildPluginBuild): void }[] }): Promise<unknown>;
}

/** esbuild is not a direct dependency of apps/mcp; borrow the copy vite already depends on. */
async function loadEsbuild(): Promise<Esbuild> {
  const viteDir = fs.realpathSync(path.join(MCP_ROOT, 'node_modules', 'vite'));
  const fromVite = createRequire(path.join(viteDir, 'package.json'));
  return (await import(pathToFileURL(fromVite.resolve('esbuild')).href)) as Esbuild;
}

export interface PrepareResult {
  outDir: string;
  bundle: string;
  externals: string[];
}

export async function prepareDeploy(outDir = path.join(MCP_ROOT, 'deploy')): Promise<PrepareResult> {
  const esbuild = await loadEsbuild();
  // Regenerate everything except deploy/.mcp-use/ (mcp-use keeps the link to the
  // Manufact server there; deleting it would make the next deploy create a new server).
  for (const entry of fs.existsSync(outDir) ? fs.readdirSync(outDir) : []) {
    if (entry !== '.mcp-use' && entry !== 'node_modules') fs.rmSync(path.join(outDir, entry), { recursive: true, force: true });
  }
  fs.mkdirSync(path.join(outDir, 'src'), { recursive: true });

  const bundle = path.join(outDir, 'src', 'server.js');
  const externals = new Set<string>();
  await esbuild.build({
    absWorkingDir: MCP_ROOT,
    entryPoints: ['src/server.ts'],
    outfile: bundle,
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node22',
    legalComments: 'none',
    logLevel: 'warning',
    banner: { js: '// Generated by apps/mcp/scripts/prepare-deploy.ts. Do not edit.' },
    plugins: [
      {
        name: 'externalize-registry-deps',
        setup(b: EsbuildPluginBuild) {
          // Bundle relative imports and @y/* workspace packages; everything else bare stays external.
          b.onResolve({ filter: /^[^./]/ }, (args) => {
            if (args.path.startsWith('node:') || args.path.startsWith('@y/')) return undefined;
            const name = args.path.startsWith('@') ? args.path.split('/').slice(0, 2).join('/') : args.path.split('/')[0]!;
            externals.add(name);
            return { path: args.path, external: true };
          });
        },
      },
    ],
  });

  const unknown = [...externals].filter((e) => !(RUNTIME_DEPS as readonly string[]).includes(e));
  if (unknown.length) throw new Error(`prepare-deploy: bundle imports undeclared packages: ${unknown.join(', ')}`);

  const src = JSON.parse(fs.readFileSync(path.join(MCP_ROOT, 'package.json'), 'utf8')) as { engines?: unknown };
  const pkg = {
    name: 'y-mcp',
    version: '0.0.0',
    private: true,
    type: 'module',
    scripts: {
      build: 'mcp-use build --entry src/server.js',
      start: 'mcp-use start --host 0.0.0.0',
    },
    dependencies: Object.fromEntries(RUNTIME_DEPS.map((d) => [d, installedVersion(d)])),
    devDependencies: Object.fromEntries(BUILD_DEPS.map((d) => [d, installedVersion(d)])),
    engines: src.engines ?? { node: '>=22.22.2' },
  };
  fs.writeFileSync(path.join(outDir, 'package.json'), `${JSON.stringify(pkg, null, 2)}\n`);
  fs.cpSync(path.join(MCP_ROOT, 'skills'), path.join(outDir, 'skills'), { recursive: true });
  fs.writeFileSync(path.join(outDir, '.gitignore'), 'node_modules/\n.mcp-use/\n.env*\nmcp-env.d.ts\n');
  return { outDir, bundle, externals: [...externals].sort() };
}

const isMain = process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) {
  const r = await prepareDeploy(process.argv[2] ? path.resolve(process.argv[2]) : undefined);
  console.log(`prepared ${path.relative(process.cwd(), r.outDir) || '.'} (externals: ${r.externals.join(', ')})`);
}
