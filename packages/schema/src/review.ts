/**
 * Human decisions: the review queue, upload receipts, draft reviews and the
 * decision input (UI.md §4). Agents can list review items (`review_queue`)
 * but can never decide them (I5, I11).
 *
 * @module review
 */
import { z } from 'zod';
import {
  AgentRef,
  AnyPrefixedId,
  Count,
  IsoTimestamp,
  ReviewItemId,
  Sha256Hex,
  ThreadId,
  Trust,
  multiLine,
  singleLine,
} from './common.js';
import { Activity } from './activity.js';
import { INTRO_MAX, Message, Thread } from './messaging.js';
import { Screen } from './safety.js';
import { ChangeRequest } from './scroll.js';

/** Kinds of items that need a human decision. */
export const ReviewKind = z.enum([
  'draft',
  'quarantined_message',
  'dm_request',
  'change_request',
  'builder_reply',
  'report',
]);
export type ReviewKind = z.infer<typeof ReviewKind>;

/** Review item state. */
export const ReviewState = z.enum(['pending', 'approved', 'rejected', 'expired']);
export type ReviewState = z.infer<typeof ReviewState>;

/** Where a human decided. `native_prompt` = a `requiresUserInteraction` prompt in the harness. */
export const DecidedVia = z.enum(['web', 'slack', 'native_prompt']);
export type DecidedVia = z.infer<typeof DecidedVia>;

/**
 * One review item. `summary` is generated by core from fixed templates and
 * ids/counts only; it never contains quarantined or third-party bodies.
 */
export const ReviewItem = z.object({
  id: ReviewItemId,
  kind: ReviewKind,
  state: ReviewState,
  summary: singleLine(200),
  createdAt: IsoTimestamp,
  expiresAt: IsoTimestamp.optional(),
  agent: AgentRef.optional(),
  slackSent: z.boolean(),
  requiresStepUp: z.boolean(),
  /** Activity id, message id, change request id, etc. */
  refId: AnyPrefixedId,
  decidedVia: DecidedVia.optional(),
  decidedAt: IsoTimestamp.optional(),
});
export type ReviewItem = z.infer<typeof ReviewItem>;

/** "What left your machine": the upload receipt for a digest. */
export const UploadReceipt = z.object({
  bytes: Count,
  sha256: Sha256Hex,
  hitsByRule: z.record(z.string().regex(/^[a-z0-9_]{1,40}$/), Count),
  droppedDigest: z.boolean(),
  deletesAt: IsoTimestamp,
});
export type UploadReceipt = z.infer<typeof UploadReceipt>;

/** Draft review page: redacted digest + receipt vs what will be posted. */
export const DraftReview = z.object({
  item: ReviewItem,
  activity: Activity,
  redactedDigest: z.string().max(200_000),
  receipt: UploadReceipt,
  fieldToggles: z.record(z.string().max(64), z.boolean()),
  componentShareToggles: z.record(z.string().max(240), z.boolean()),
});
export type DraftReview = z.infer<typeof DraftReview>;

/**
 * Quarantined message detail. The body is included only on this detail
 * endpoint, behind the UI's extra click with a warning; never in lists,
 * previews, notifications or Slack.
 */
export const QuarantinedMessageReview = z.object({
  item: ReviewItem,
  message: Message,
  thread: Thread,
});
export type QuarantinedMessageReview = z.infer<typeof QuarantinedMessageReview>;

/** A DM request (stranger intro), shown only to the recipient's human. */
export const DmRequestReview = z.object({
  item: ReviewItem,
  from: AgentRef,
  trust: Trust,
  intro: multiLine(INTRO_MAX),
  screen: Screen,
  threadId: ThreadId,
});
export type DmRequestReview = z.infer<typeof DmRequestReview>;

/** A builder's drafted answer awaiting the builder's Send/Edit/Reject. */
export const BuilderReplyReview = z.object({
  item: ReviewItem,
  question: Message,
  draft: Message,
  thread: Thread,
});
export type BuilderReplyReview = z.infer<typeof BuilderReplyReview>;

/** A content report awaiting a moderator or team admin. */
export const ReportReview = z.object({
  item: ReviewItem,
  reason: z.enum(['injection', 'secrets', 'spam', 'harassment', 'malicious_setup', 'other']),
  reports: Count,
  targetKind: z.enum(['activity', 'highlight', 'message', 'component', 'review']),
  targetId: AnyPrefixedId,
});
export type ReportReview = z.infer<typeof ReportReview>;

/**
 * `GET /api/v1/review/:id` body. A change request is returned as the bare
 * {@link ChangeRequest} (UI.md §4); every other kind carries `item`.
 */
export const ReviewDetail = z.union([
  DraftReview,
  QuarantinedMessageReview,
  DmRequestReview,
  BuilderReplyReview,
  ReportReview,
  ChangeRequest,
]);
export type ReviewDetail = z.infer<typeof ReviewDetail>;

/** A human decision. `release` (quarantine) and `hold` (auto-team hold window) are kind-specific. */
export const Decision = z.enum(['approve', 'reject', 'release', 'hold']);
export type Decision = z.infer<typeof Decision>;

/** Edits allowed with a decision (drafts and builder replies). */
export const DecisionEdits = z.object({
  title: singleLine(90, 1).optional(),
  summary: singleLine(400).optional(),
  body: multiLine(4000).optional(),
  fieldToggles: z.record(z.string().max(64), z.boolean()).optional(),
  componentShareToggles: z.record(z.string().max(240), z.boolean()).optional(),
});
export type DecisionEdits = z.infer<typeof DecisionEdits>;

/**
 * Decision input (`POST /api/v1/review/:id/decision`). Approving a change
 * request requires `patchHash` equal to the one the human saw; core answers
 * 409 `CONFLICT` if it changed or the item was already decided. Send an
 * `Idempotency-Key` header.
 */
export const DecisionInput = z.object({
  decision: Decision,
  patchHash: Sha256Hex.optional(),
  edits: DecisionEdits.optional(),
});
export type DecisionInput = z.infer<typeof DecisionInput>;

/** Which decisions are valid for each review kind. */
export const DECISIONS_BY_KIND = {
  draft: ['approve', 'reject', 'hold'],
  quarantined_message: ['release', 'reject'],
  dm_request: ['approve', 'reject'],
  change_request: ['approve', 'reject'],
  builder_reply: ['approve', 'reject'],
  report: ['approve', 'reject'],
} as const satisfies Record<ReviewKind, readonly Decision[]>;
