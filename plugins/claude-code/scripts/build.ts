/**
 * Bundle the hook entry points into scripts/dist/*.mjs (node20, ESM). The
 * workspace libraries (@y/capture, redact, pointers, schema) and zod
 * are bundled in; the output has no runtime dependencies beyond node.
 * Reproducible: no timestamps, no sourcemaps, stable entry names.
 */
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import * as path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

await build({
  absWorkingDir: root,
  entryPoints: {
    hook: 'src/entries/hook.ts',
    uploader: 'src/entries/uploader.ts',
    listen: 'src/entries/listen.ts',
  },
  outdir: 'scripts/dist',
  outExtension: { '.js': '.mjs' },
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  splitting: false,
  minify: false,
  treeShaking: true,
  legalComments: 'none',
  charset: 'utf8',
  logLevel: 'info',
  banner: { js: '// Generated by plugins/claude-code/scripts/build.ts. Do not edit.' },
});
